#!/usr/bin/env python3
"""Generate core/infinity_figure_table.inc from RPCS3's infinity_dialog.cpp.

usage: gen_figure_table.py <path/to/infinity_dialog.cpp> <out.inc>
"""
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()
entries = re.findall(r'\{0x([0-9A-Fa-f]+),\s*\{(\d),\s*"((?:[^"\\]|\\.)*)"\}\}', src)
if not entries:
    sys.exit("no figure entries found")

rows = sorted((int(i, 16), int(s), n) for i, s, n in entries)
if len({r[0] for r in rows}) != len(rows):
    sys.exit("duplicate figure ids")

with open(sys.argv[2], "w", encoding="utf-8") as out:
    out.write("/* Generated by tools/gen_figure_table.py from RPCS3's infinity_dialog.cpp. */\n")
    for ident, series, name in rows:
        out.write('    {0x%06X, %d, "%s"},\n' % (ident, series, name.replace('"', '\\"')))
print(len(rows), "figures")
